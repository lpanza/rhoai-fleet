#!/usr/bin/env bash
# Render the fake-gpu-operator chart into plain manifests for the PolicyGenerator.
# Re-run after changing chart/values.yaml or CHART_VERSION, and commit the result.
set -euo pipefail
cd "$(dirname "$0")"

CHART_VERSION=0.2.1
export NAMESPACE=fake-gpu-operator
OUT=manifests/fake-gpu-operator.yaml

helm template fake-gpu-operator \
  oci://ghcr.io/run-ai/fake-gpu-operator/fake-gpu-operator \
  --version "${CHART_VERSION}" \
  --namespace "${NAMESPACE}" \
  --skip-crds \
  -f chart/values.yaml |
# Drop objects that are wrong for this setup:
#  - a fake NVIDIA GPU Operator CSV written into openshift-operator-lifecycle-manager
#  - a ClusterRole/Binding named clusterlogging-collector-metrics (collides with OpenShift Logging)
#  - the KWOK dcgm-exporter (no KWOK nodes) and the dummy replicas-0 "gpu-operator" Deployment
#  - empty documents
# and put every namespaced object in ${NAMESPACE}.
yq eval-all '
  select(. != null and .kind != null)
  | select(.kind != "ClusterServiceVersion")
  | select(.metadata.name != "clusterlogging-collector-metrics")
  | select(.metadata.name != "nvidia-dcgm-exporter-kwok")
  | select(.kind != "Deployment" or .metadata.name != "gpu-operator")
  | (select(.kind != "ClusterRole" and .kind != "ClusterRoleBinding") | .metadata.namespace) = strenv(NAMESPACE)
  | del(.metadata.labels."helm.sh/chart")
' |
# CRI-O on OpenShift enforces short-name resolution: fully qualify Docker Hub images.
sed -E 's#image: "ubuntu:#image: "docker.io/library/ubuntu:#' > "${OUT}.tmp"
{
  echo "# GENERATED by render.sh from fake-gpu-operator ${CHART_VERSION}. Do not edit by hand."
  cat "${OUT}.tmp"
} > "${OUT}"
rm -f "${OUT}.tmp"
echo "wrote ${OUT}: $(grep -c '^kind:' "${OUT}") objects"
